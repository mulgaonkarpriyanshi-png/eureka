create table if not exists public.callback_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  contact text not null,
  message text not null,
  tour_title text,
  source text not null default 'homepage_featured_tours',
  status text not null default 'new'
);

alter table public.callback_requests enable row level security;

drop policy if exists "Allow public callback submissions" on public.callback_requests;
create policy "Allow public callback submissions"
on public.callback_requests
for insert
to anon
with check (true);

grant insert on table public.callback_requests to anon;
grant usage, select on sequence public.callback_requests_id_seq to anon;
revoke select, update, delete on table public.callback_requests from anon;
